"""How fusion's risk-shifted threshold changes late-blight precision and recall.

For every image in the CNN test set (data/splits/test.csv, the same 324 images
as the Colab notebook), the deployed TFLite model gives p_late through the
server's own preprocessing (backend/cnn_service.py). Then, for each weather
risk r in R_VALUES, fusion's threshold tau(r) decides which images would be
flagged as late blight, and precision / recall / F1 are computed against the
true labels.

This is a SENSITIVITY ANALYSIS, not an evaluation of the weather model: the
PlantVillage photos have no weather attached, so every image is scored as if
the risk were r. It answers "how much does the weather move the late-blight
call for this CNN?".

    .\\.venv\\Scripts\\python.exe -m ml.fusion_eval

Writes docs/fusion_eval.md (and docs/fusion_eval.json).
"""
import csv
import json
from datetime import UTC, datetime

import numpy as np

from backend import cnn_service, fusion
from backend.config import REPO_ROOT

R_VALUES = (0.1, 0.3, 0.5, 0.7, 0.9)
TEST_SPLIT = REPO_ROOT / "data" / "splits" / "test.csv"
REPORT = REPO_ROOT / "docs" / "fusion_eval.md"


def sweep(is_late: np.ndarray, p_late: np.ndarray, r_values=R_VALUES) -> list[dict]:
    """Precision / recall / F1 for late blight at each r. Pure function, tested."""
    rows = []
    for r in r_values:
        tau = fusion.threshold_for(r)
        flagged = p_late >= tau
        tp = int((flagged & is_late).sum())
        fp = int((flagged & ~is_late).sum())
        fn = int((~flagged & is_late).sum())
        precision = tp / (tp + fp) if tp + fp else None
        recall = tp / (tp + fn) if tp + fn else None
        f1 = (2 * precision * recall / (precision + recall)
              if precision and recall else (0.0 if precision is not None and recall is not None else None))
        rows.append({"r": r, "tau": tau, "flagged": int(flagged.sum()), "tp": tp, "fp": fp, "fn": fn,
                     "precision": precision, "recall": recall, "f1": f1})
    return rows


def borderline(p_late: np.ndarray, r_values=R_VALUES) -> np.ndarray:
    """Images whose late-blight call depends on r: p_late between the lowest and highest tau."""
    taus = [fusion.threshold_for(r) for r in r_values]
    return (p_late >= min(taus)) & (p_late < max(taus))


def _f(value):
    return "n/a" if value is None else f"{value:.3f}"


def render(rows, n_images, n_late, n_borderline, borderline_rows, model_name) -> str:
    lines = [
        "# Fusion: late-blight precision and recall across the weather risk r",
        "",
        "Generated by `ml/fusion_eval.py`. The same CNN outputs, gated by "
        f"tau(r) = clip({fusion.TAU0} − {fusion.K} × (r − 0.5), {fusion.TAU_MIN}, {fusion.TAU_MAX}).",
        "",
        f"- Images: the CNN test split (`data/splits/test.csv`), {n_images} images, {n_late} truly late blight.",
        f"- Model: `{model_name}` through the server's preprocessing (`backend/cnn_service.py`).",
        f"- Run: {datetime.now(UTC):%Y-%m-%d %H:%M UTC}.",
        "- A sensitivity analysis: the photos carry no weather, so every image is scored as if the risk were r.",
        "",
        "| r | tau(r) | Flagged | True positives | False positives | Missed | Precision | Recall | F1 |",
        "|---|---|---|---|---|---|---|---|---|",
        *[f"| {row['r']:.1f} | {row['tau']:.2f} | {row['flagged']} | {row['tp']} | {row['fp']} | {row['fn']} | "
          f"{_f(row['precision'])} | {_f(row['recall'])} | {_f(row['f1'])} |" for row in rows],
        "",
        "## What this shows",
        "",
        f"- **{n_borderline} of {n_images} test images** have a late-blight probability between the lowest "
        f"and highest threshold ({min(r['tau'] for r in rows):.2f} to {max(r['tau'] for r in rows):.2f}), so "
        "only their call can change with the weather. Every other image is flagged, or not, whatever r is.",
    ]
    if n_borderline:
        lines.append("- Those images: " + "; ".join(
            f"{b['file']} (true {b['label']}, p_late {b['p_late']:.3f})" for b in borderline_rows) + ".")
    lines += [
        "- On PlantVillage the CNN is nearly always very sure (clean leaves on plain backgrounds), so the "
        "weather has little left to decide here. Fusion is designed for the uncertain middle: field photos "
        "against soil and foliage, which `ml/eval_cnn.py` measures once the farmer's photos exist. Re-run "
        "this sweep on those to see the effect where it matters.",
        "- Direction, as designed: higher r lowers tau, so recall can only rise and precision can only fall "
        "(or stay the same) as the weather turns favourable.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    if not cnn_service.load_classifier():
        print("Model not found: put cnn.tflite and labels.txt in models/")
        return 1
    classifier = cnn_service._classifier

    with TEST_SPLIT.open(newline="", encoding="utf-8") as handle:
        items = [(REPO_ROOT / row["filepath"], row["label"]) for row in csv.DictReader(handle)]
    p_late = np.array([
        classifier.predict(cnn_service.preprocess(path.read_bytes())).probabilities[fusion.LATE_BLIGHT]
        for path, _ in items
    ])
    is_late = np.array([label == fusion.LATE_BLIGHT for _, label in items])

    rows = sweep(is_late, p_late)
    mask = borderline(p_late)
    borderline_rows = [{"file": items[i][0].name, "label": items[i][1], "p_late": float(p_late[i])}
                       for i in np.flatnonzero(mask)]
    REPORT.write_text(render(rows, len(items), int(is_late.sum()), int(mask.sum()), borderline_rows,
                             cnn_service.MODEL_PATH.name), encoding="utf-8")
    REPORT.with_suffix(".json").write_text(json.dumps(
        {"rows": rows, "borderline": borderline_rows, "images": len(items)}, indent=2) + "\n", encoding="utf-8")

    print(f"{'r':>4} {'tau':>5} {'flag':>5} {'prec':>6} {'rec':>6} {'F1':>6}")
    for row in rows:
        print(f"{row['r']:4.1f} {row['tau']:5.2f} {row['flagged']:5d} {_f(row['precision']):>6} "
              f"{_f(row['recall']):>6} {_f(row['f1']):>6}")
    print(f"Borderline images (call depends on r): {int(mask.sum())} of {len(items)}")
    print(f"Wrote {REPORT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
